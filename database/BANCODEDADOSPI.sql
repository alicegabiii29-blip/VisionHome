CREATE DATABASE BANCO_DE_DADOS_PI CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE BANCO_DE_DADOS_PI;

CREATE TABLE USUARIOS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(150) NOT NULL,
    USUARIO VARCHAR(50) UNIQUE NOT NULL,
    EMAIL VARCHAR(150) UNIQUE DEFAULT NULL,
    SENHA VARCHAR(255) NOT NULL,
    CPF_CNPJ VARCHAR(20) UNIQUE DEFAULT NULL,
    TELEFONE VARCHAR(20) DEFAULT NULL,
    TIPO ENUM('CLIENTE', 'CORRETOR', 'ADMIN') DEFAULT 'CLIENTE',
    CRECI VARCHAR(30) DEFAULT NULL,
    ESTADO ENUM('ATIVO', 'INATIVO', 'BLOQUEADO') DEFAULT 'ATIVO',
    CRIADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ATUALIZADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IMOVEIS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    PROPRIETARIO_ID INT NOT NULL,
    TITULO VARCHAR(150) NOT NULL,
    DESCRICAO TEXT NOT NULL,
    TIPO ENUM('CASA', 'APARTAMENTO', 'TERRENO', 'COMERCIAL', 'CHACARA') NOT NULL,
    FINALIDADE ENUM('VENDA', 'ALUGUEL', 'AMBOS') NOT NULL,
    PRECO_VENDA DECIMAL(12, 2) DEFAULT NULL,
    PRECO_ALUGUEL DECIMAL(10, 2) DEFAULT NULL,
    VALOR_CONDOMINIO DECIMAL(10, 2) DEFAULT 0.00,
    VALOR_IPTU DECIMAL(10, 2) DEFAULT 0.00,
    CEP VARCHAR(10) NOT NULL,
    ENDERECO VARCHAR(255) NOT NULL,
    NUMERO VARCHAR(20),
    COMPLEMENTO VARCHAR(100),
    BAIRRO VARCHAR(100) NOT NULL,
    CIDADE VARCHAR(100) NOT NULL,
    UF VARCHAR(2) NOT NULL,
    QUARTOS INT DEFAULT 0,
    BANHEIROS INT DEFAULT 0,
    VAGAS_GARAGEM INT DEFAULT 0,
    AREA_TOTAL DECIMAL(10, 2) NOT NULL,
    AREA_UTIL DECIMAL(10, 2) DEFAULT NULL,
    STATUS ENUM('DISPONIVEL', 'RESERVADO', 'VENDIDO', 'ALUGADO', 'INATIVO') DEFAULT 'DISPONIVEL',
    DESTAQUE BOOLEAN DEFAULT FALSE,
    CRIADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ATUALIZADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (PROPRIETARIO_ID) REFERENCES USUARIOS(ID)
);

CREATE TABLE CARACTERISTICAS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    ICONE VARCHAR(50) DEFAULT NULL
);

CREATE TABLE IMOVEL_CARACTERISTICAS (
    IMOVEL_ID INT NOT NULL,
    CARACTERISTICA_ID INT NOT NULL,
    PRIMARY KEY (IMOVEL_ID, CARACTERISTICA_ID),
    FOREIGN KEY (IMOVEL_ID) REFERENCES IMOVEIS(ID) ON DELETE CASCADE,
    FOREIGN KEY (CARACTERISTICA_ID) REFERENCES CARACTERISTICAS(ID) ON DELETE CASCADE
);

CREATE TABLE IMAGENS_IMOVEIS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    IMOVEL_ID INT NOT NULL,
    URL_IMAGEM VARCHAR(255) NOT NULL,
    ORDEM INT DEFAULT 0,
    DESTAQUE BOOLEAN DEFAULT FALSE,
    FOREIGN KEY (IMOVEL_ID) REFERENCES IMOVEIS(ID) ON DELETE CASCADE
);

CREATE TABLE AGENDAMENTOS_VISITAS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    IMOVEL_ID INT NOT NULL,
    CLIENTE_ID INT NOT NULL,
    CORRETOR_ID INT NOT NULL,
    DATA_HORA DATETIME NOT NULL,
    ESTADO ENUM('PENDENTE', 'CONFIRMADO', 'REALIZADO', 'CANCELADO') DEFAULT 'PENDENTE',
    OBSERVACOES TEXT,
    CRIADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (IMOVEL_ID) REFERENCES IMOVEIS(ID) ON DELETE CASCADE,
    FOREIGN KEY (CLIENTE_ID) REFERENCES USUARIOS(ID),
    FOREIGN KEY (CORRETOR_ID) REFERENCES USUARIOS(ID)
);

CREATE TABLE PROPOSTAS_IMOVEIS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    IMOVEL_ID INT NOT NULL,
    CLIENTE_ID INT NOT NULL,
    CORRETOR_ID INT DEFAULT NULL,
    TIPO_PROPOSTA ENUM('VENDA', 'ALUGUEL') NOT NULL,
    VALOR_OFERTADO DECIMAL(12, 2) NOT NULL,
    CONDICOES_PAGAMENTO TEXT,
    ESTADO ENUM('ANALISE', 'ACEITA', 'RECUSADA', 'CONTRAPROPOSTA') DEFAULT 'ANALISE',
    CRIADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (IMOVEL_ID) REFERENCES IMOVEIS(ID),
    FOREIGN KEY (CLIENTE_ID) REFERENCES USUARIOS(ID),
    FOREIGN KEY (CORRETOR_ID) REFERENCES USUARIOS(ID)
);

CREATE TABLE CONTRATOS_IMOVEIS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    IMOVEL_ID INT NOT NULL,
    CLIENTE_ID INT NOT NULL,
    CORRETOR_ID INT NOT NULL,
    PROPOSTA_ID INT DEFAULT NULL,
    TIPO_CONTRATO ENUM('VENDA', 'ALUGUEL') NOT NULL,
    VALOR_TOTAL DECIMAL(12, 2) NOT NULL,
    DATA_INICIO DATE NOT NULL,
    DATA_FIM DATE DEFAULT NULL,
    DIA_VENCIMENTO_ALUGUEL INT DEFAULT NULL,
    ESTADO ENUM('ATIVO', 'ENCERRADO', 'CANCELADO') DEFAULT 'ATIVO',
    CRIADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (IMOVEL_ID) REFERENCES IMOVEIS(ID),
    FOREIGN KEY (CLIENTE_ID) REFERENCES USUARIOS(ID),
    FOREIGN KEY (CORRETOR_ID) REFERENCES USUARIOS(ID),
    FOREIGN KEY (PROPOSTA_ID) REFERENCES PROPOSTAS_IMOVEIS(ID)
);

CREATE TABLE CATEGORIAS_DECORACAO (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    SLUG VARCHAR(100) UNIQUE NOT NULL,
    DESCRICAO TEXT
);

CREATE TABLE PRODUTOS_DECORACAO (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    CATEGORIA_ID INT NOT NULL,
    NOME VARCHAR(150) NOT NULL,
    SLUG VARCHAR(150) UNIQUE NOT NULL,
    DESCRICAO TEXT NOT NULL,
    PRECO DECIMAL(10, 2) NOT NULL,
    PRECO_PROMOCIONAL DECIMAL(10, 2) DEFAULT NULL,
    ESTOQUE INT DEFAULT 0,
    SKU VARCHAR(50) UNIQUE NOT NULL,
    PESO_KG DECIMAL(6, 2) DEFAULT 0.00,
    LARGURA_CM DECIMAL(6, 2) DEFAULT 0.00,
    ALTURA_CM DECIMAL(6, 2) DEFAULT 0.00,
    PROFUNDIDADE_CM DECIMAL(6, 2) DEFAULT 0.00,
    ESTADO ENUM('ATIVO', 'INATIVO', 'ESGOTADO') DEFAULT 'ATIVO',
    CRIADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIAS_DECORACAO(ID)
);

CREATE TABLE IMAGENS_PRODUTOS_DECORACAO (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    PRODUTO_ID INT NOT NULL,
    URL_IMAGEM VARCHAR(255) NOT NULL,
    DESTAQUE BOOLEAN DEFAULT FALSE,
    FOREIGN KEY (PRODUTO_ID) REFERENCES PRODUTOS_DECORACAO(ID) ON DELETE CASCADE
);

CREATE TABLE CARRINHO_ITENS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    USUARIO_ID INT NOT NULL,
    PRODUTO_ID INT NOT NULL,
    QUANTIDADE INT NOT NULL CHECK (QUANTIDADE > 0),
    CRIADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID) ON DELETE CASCADE,
    FOREIGN KEY (PRODUTO_ID) REFERENCES PRODUTOS_DECORACAO(ID) ON DELETE CASCADE
);

CREATE TABLE PEDIDOS_DECORACAO (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    CLIENTE_ID INT NOT NULL,
    IMOVEL_ID INT DEFAULT NULL,
    VALOR_SUBTOTAL DECIMAL(10, 2) NOT NULL,
    VALOR_FRETE DECIMAL(10, 2) NOT NULL,
    VALOR_TOTAL DECIMAL(10, 2) NOT NULL,
    ESTADO ENUM('AGUARDANDO_PAGAMENTO', 'PAGO', 'SEPARACAO', 'ENVIADO', 'ENTREGUE', 'CANCELADO') DEFAULT 'AGUARDANDO_PAGAMENTO',
    CEP_ENTREGA VARCHAR(10) NOT NULL,
    ENDERECO_ENTREGA VARCHAR(255) NOT NULL,
    NUMERO_ENTREGA VARCHAR(20),
    COMPLEMENTO_ENTREGA VARCHAR(100),
    BAIRRO_ENTREGA VARCHAR(100) NOT NULL,
    CIDADE_ENTREGA VARCHAR(100) NOT NULL,
    ESTADO_ENTREGA VARCHAR(2) NOT NULL,
    CRIADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (CLIENTE_ID) REFERENCES USUARIOS(ID),
    FOREIGN KEY (IMOVEL_ID) REFERENCES IMOVEIS(ID) ON DELETE SET NULL
);

CREATE TABLE ITENS_PEDIDO_DECORACAO (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    PEDIDO_ID INT NOT NULL,
    PRODUTO_ID INT NOT NULL,
    QUANTIDADE INT NOT NULL,
    PRECO_UNITARIO DECIMAL(10, 2) NOT NULL,
    FOREIGN KEY (PEDIDO_ID) REFERENCES PEDIDOS_DECORACAO(ID) ON DELETE CASCADE,
    FOREIGN KEY (PRODUTO_ID) REFERENCES PRODUTOS_DECORACAO(ID)
);

CREATE TABLE FAVORITOS_IMOVEIS (
    USUARIO_ID INT NOT NULL,
    IMOVEL_ID INT NOT NULL,
    PRIMARY KEY (USUARIO_ID, IMOVEL_ID),
    FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID) ON DELETE CASCADE,
    FOREIGN KEY (IMOVEL_ID) REFERENCES IMOVEIS(ID) ON DELETE CASCADE
);

CREATE TABLE FAVORITOS_DECORACAO (
    USUARIO_ID INT NOT NULL,
    PRODUTO_ID INT NOT NULL,
    PRIMARY KEY (USUARIO_ID, PRODUTO_ID),
    FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID) ON DELETE CASCADE,
    FOREIGN KEY (PRODUTO_ID) REFERENCES PRODUTOS_DECORACAO(ID) ON DELETE CASCADE
);

CREATE TABLE AVALIACOES_PRODUTOS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    PRODUTO_ID INT NOT NULL,
    CLIENTE_ID INT NOT NULL,
    NOTA INT CHECK (NOTA BETWEEN 1 AND 5),
    COMENTARIO TEXT,
    CRIADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (PRODUTO_ID) REFERENCES PRODUTOS_DECORACAO(ID) ON DELETE CASCADE,
    FOREIGN KEY (CLIENTE_ID) REFERENCES USUARIOS(ID)
);

CREATE TABLE PAGAMENTOS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    PEDIDO_DECORACAO_ID INT DEFAULT NULL,
    CONTRATO_IMOVEL_ID INT DEFAULT NULL,
    VALOR DECIMAL(10, 2) NOT NULL,
    METODO_PAGAMENTO ENUM('CARTAO_CREDITO', 'PIX', 'BOLETO') NOT NULL,
    ESTADO_PAGAMENTO ENUM('PENDENTE', 'APROVADO', 'RECUSADO', 'REEMBOLSADO') DEFAULT 'PENDENTE',
    TRANSACAO_GATEWAY_ID VARCHAR(150) DEFAULT NULL,
    CRIADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (PEDIDO_DECORACAO_ID) REFERENCES PEDIDOS_DECORACAO(ID) ON DELETE SET NULL,
    FOREIGN KEY (CONTRATO_IMOVEL_ID) REFERENCES CONTRATOS_IMOVEIS(ID) ON DELETE SET NULL
);


